import { en, type DictKey } from "./en";

export type NorthwingDictKey = Extract<DictKey, `northwing.${string}`>;

const keys = Object.keys(en).filter((key): key is NorthwingDictKey => key.startsWith("northwing."));

function buildNorthwingDictionary(locale: string, values: readonly string[]): Record<NorthwingDictKey, string> {
  if (values.length !== keys.length) {
    throw new Error(`Northwing ${locale} dictionary has ${values.length} values for ${keys.length} keys`);
  }
  return Object.fromEntries(keys.map((key, index) => [key, values[index]])) as Record<NorthwingDictKey, string>;
}

